-- Viaggi RSM (privati): del soggetto o dell'astrologo, mai di entrambi (D14, D15).
CREATE TABLE viaggi_rsm (
    id               BIGSERIAL PRIMARY KEY,
    utente_id        INTEGER REFERENCES utenti(id) ON DELETE CASCADE,
    soggetto_id      INTEGER REFERENCES soggetti(id) ON DELETE CASCADE,
    sessione_rs_id   INTEGER REFERENCES sessioni_rs(id) ON DELETE SET NULL,
    luogo            VARCHAR(200) NOT NULL,
    iso_nazione      CHAR(2) NOT NULL REFERENCES nazioni(iso),
    latitudine       NUMERIC(9,6),
    longitudine      NUMERIC(9,6),
    data_arrivo      DATE,
    data_partenza    DATE,
    albergo          VARCHAR(200),
    costo_alloggio   NUMERIC(10,2),
    costo_trasporti  NUMERIC(10,2),
    valuta           CHAR(3) NOT NULL DEFAULT 'EUR',
    trasporti        TEXT,
    note_private     TEXT,
    creato_il        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT viaggi_rsm_autore_check CHECK ((utente_id IS NULL) <> (soggetto_id IS NULL)),
    CONSTRAINT viaggi_rsm_luogo_check CHECK (luogo = btrim(luogo) AND luogo <> ''),
    CONSTRAINT viaggi_rsm_date_check CHECK (data_partenza IS NULL OR data_arrivo IS NULL OR data_partenza >= data_arrivo),
    CONSTRAINT viaggi_rsm_costi_check CHECK (COALESCE(costo_alloggio, 0) >= 0 AND COALESCE(costo_trasporti, 0) >= 0),
    CONSTRAINT viaggi_rsm_valuta_check CHECK (valuta ~ '^[A-Z]{3}$'),
    CONSTRAINT viaggi_rsm_testi_check CHECK (COALESCE(char_length(trasporti), 0) <= 4000 AND COALESCE(char_length(note_private), 0) <= 4000)
);

CREATE INDEX idx_viaggi_rsm_utente ON viaggi_rsm (utente_id);
CREATE INDEX idx_viaggi_rsm_soggetto ON viaggi_rsm (soggetto_id);

-- Contributi condivisi: solo dati di viaggio, mai dati del soggetto (regola del par. 2).
