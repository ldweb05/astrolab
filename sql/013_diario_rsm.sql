    info_lingua_valuta          TEXT,
    info_connettivita           TEXT,
    info_particolarita          TEXT,
    contatti_utili              TEXT,
    consigli                    TEXT,
    dichiarazione_contatti      BOOLEAN NOT NULL,
    visibile                    BOOLEAN NOT NULL DEFAULT TRUE,
    creato_il                   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT contributi_autore_check CHECK (utente_id IS NULL OR soggetto_id IS NULL),
    CONSTRAINT contributi_luogo_check CHECK (luogo = btrim(luogo) AND luogo <> ''),
    CONSTRAINT contributi_anno_check CHECK (anno_viaggio BETWEEN 1900 AND 2100),
    CONSTRAINT contributi_mese_check CHECK (mese_viaggio IS NULL OR mese_viaggio BETWEEN 1 AND 12),
    CONSTRAINT contributi_alloggio_tipo_check CHECK (alloggio_tipo IS NULL OR alloggio_tipo IN
        ('hotel', 'bb', 'appartamento', 'guesthouse', 'campeggio', 'altro')),
    CONSTRAINT contributi_alloggio_sito_check CHECK (alloggio_sito IS NULL OR alloggio_sito ~* '^https?://'),
    CONSTRAINT contributi_costo_check CHECK (COALESCE(costo_alloggio_indicativo, 0) >= 0),
    CONSTRAINT contributi_valuta_check CHECK (valuta ~ '^[A-Z]{3}$'),
